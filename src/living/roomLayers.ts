import type { AmbientDefinition, Cutout, Polygon } from './types'

const cut = (id: string, depth: number, polygon: Polygon): Cutout => ({ id, depth, polygon })
const motion = (id: string, kind: AmbientDefinition['kind'], polygon: Polygon, pivot: [number, number], depth: number, amplitude: number, activity?: string): AmbientDefinition => ({
  id, kind, polygon, pivot: { x: pivot[0], y: pivot[1] }, depth, amplitude, activity,
  minDelay: kind === 'lamp' ? 70 : kind === 'paper' ? 45 : kind === 'cursor' ? 20 : 30,
  maxDelay: kind === 'lamp' ? 140 : kind === 'paper' ? 105 : kind === 'cursor' ? 55 : 90,
  duration: kind === 'wheel' ? 4 : kind === 'cursor' ? 2.5 : kind === 'lamp' ? 7 : kind === 'leaf' ? 6 : 5,
  probability: activity ? 0.95 : kind === 'lamp' ? 0.65 : 0.8,
})

